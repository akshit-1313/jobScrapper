--   * f379016f-2c06-4677-8daa-3110534179cc — "Unknown Title / Unknown Company",
--     an empty extraction from jobs.lever.co with no description.
--
-- WHY AN EXPLICIT ID LIST
-- No predicate is used. Not `score < 30`, not a title or company LIKE, not an
-- id prefix. A predicate would silently widen as data changes; this list is
-- auditable and cannot match a row nobody reviewed. If an id has already been
-- removed the statement simply matches nothing.
--
-- THE SCORE RULE DOES NOT APPLY HERE
-- Dummy data is removed because it is dummy, independently of its score. Two of
-- these fixtures matter for that distinction:
--   b0000000-...-000000000003  GitLab            27.00  (below 30)
--   b0000000-...-000000000015  Vercel            30.00  (exactly 30)
-- A REAL job scoring exactly 30 would be kept, and at the time of writing no
-- real job scores below 30 and no job is unscored. Both of these go only
-- because they are fixtures.
--
-- WHAT IS DELIBERATELY NOT DELETED
-- 2bc5ead5-3654-4dc6-b2dd-2c5106ace701 is also "Unknown Title / Unknown
-- Company" and is equally junk, but it carries one application and one
-- application_event. Every foreign key into jobs is ON DELETE CASCADE, and
-- application_events cascades from applications, so removing the job would
-- destroy real application history. Junk with history is kept.
--
-- CASCADE FOOTPRINT (verified before writing this migration)
-- The 26 rows carry 26 job_matches, 11 job_source_mappings, 26 job_locations
-- and 56 job_skills. All are derived data, regenerated by discovery and
-- matching. They carry ZERO applications, ZERO application_events and ZERO
-- saved_jobs — checked explicitly, and the guard below re-checks it at apply
-- time rather than trusting that snapshot.
--
