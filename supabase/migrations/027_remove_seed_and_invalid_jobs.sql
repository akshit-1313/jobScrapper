-- Guard 1: never delete a job carrying user history. This is the same check
-- performed during the audit, repeated here so the migration is safe on its
-- own terms — if Production has changed since, this aborts instead of
-- destroying history.
DO $$
DECLARE
    protected_count INTEGER;
BEGIN
    SELECT count(*) INTO protected_count
    FROM _doomed_jobs d
    WHERE EXISTS (SELECT 1 FROM public.applications a WHERE a.job_id = d.id)
       OR EXISTS (SELECT 1 FROM public.saved_jobs s WHERE s.job_id = d.id);

    IF protected_count > 0 THEN
        RAISE EXCEPTION
            'Aborting: % of the listed jobs now carry applications or saved_jobs. Re-audit before deleting.',
            protected_count;
    END IF;
END $$;

-- Guard 2: the job deliberately retained must never appear in the list.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM _doomed_jobs WHERE id = '2bc5ead5-3654-4dc6-b2dd-2c5106ace701') THEN
        RAISE EXCEPTION 'Aborting: the protected job 2bc5ead5 is in the deletion list.';
    END IF;
END $$;

DELETE FROM public.jobs j USING _doomed_jobs d WHERE j.id = d.id;

COMMIT;

